/**
  * @brief  错误处理函数
  *
  * 当系统发生严重错误时调用这个函数，比如：
  * - 外设初始化失败
  * - 断言失败
  * - 其他不可恢复的错误
  *
  * 处理方式：
  * - 关闭所有中断（防止错误扩散）
  * - LED 闪烁提示错误状态
  * - 死循环，等待用户复位
  *
  * TODO：以后可以加更完善的错误处理，
  * 比如记录错误原因、自动重启等。
  */
void Error_Handler(void)
{
    /* 禁用所有中断 —— 防止错误状态下中断继续执行 */
    __disable_irq();

    /* 死循环 + LED 闪烁指示错误
     * 用 LED 闪烁来表示系统出错了，
     * 以后可以加蜂鸣器报警或者 OLED 显示错误信息 */
    while (1) {
        /* 错误指示：LED 以 5Hz 频率闪烁（亮 200ms 灭 200ms） */
        HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_0);
        HAL_Delay(200);
    }
}

