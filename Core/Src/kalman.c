/*
 * @file kalman.c
 * @brief 卡尔曼滤波器实现
 * @author 巫伟鑫
 * @date 2024-08-12
 *
 * 【说明】
 * 本文件实现了两种卡尔曼滤波器：
 *   1. 一维卡尔曼滤波（Kalman1D）—— 最简单的卡尔曼滤波，用于单个变量的滤波
 *   2. 角度卡尔曼滤波（KalmanAngle）—— 二阶卡尔曼滤波，用于融合加速度计和陀螺仪
 *
 * 【卡尔曼滤波是什么？】
 * 卡尔曼滤波是一种最优状态估计算法，它通过一系列含有噪声的测量数据，
 * 估计系统的状态。简单说就是：把有噪声的测量值和系统模型的预测值结合起来，
 * 得到一个更准确、更平滑的估计值。
 *
 * 【核心思想】
 * 1. 预测（Predict）：根据上一时刻的状态和系统模型，预测当前时刻的状态
 * 2. 更新（Update）：用当前时刻的测量值来修正预测值，得到更准确的估计
 *
 * 【为什么叫"最优"？】
 * 在假设噪声是高斯白噪声的前提下，卡尔曼滤波是线性无偏最小方差估计，
 * 也就是说它给出的估计值是所有线性估计里误差最小的。
 * 当然实际系统不一定完全满足假设，但卡尔曼滤波在很多场景下效果都很好。
 *
 * 【学习笔记】
 * 卡尔曼滤波的数学推导真的很难，我当初看了好几天才勉强看懂。
 * 但实际用的时候发现，不需要完全搞懂推导也能用，
 * 就像你不需要懂发动机原理也能开车一样。
 * 知道 Q 和 R 这两个参数怎么调，知道怎么把数据喂进去，
 * 就能用起来了。当然，如果能搞懂原理，调参会更有方向。
 */

#include "kalman.h"

/* ================================================================
 *                       一维卡尔曼滤波
 * ================================================================ */

/**
 * @brief  一维卡尔曼滤波初始化
 * @param  kf:            卡尔曼滤波器结构体指针
 * @param  q:             过程噪声协方差（系统模型的不确定性）
 * @param  r:             测量噪声协方差（传感器的不确定性）
 * @param  initial_value: 初始估计值
 *
 * 【参数说明】
 * Q（过程噪声协方差）：
 *   表示我们对系统模型的信任程度。Q 越大，说明我们认为系统模型越不可靠，
 *   实际状态可能和预测的差得越多。
 *   Q 越大 → 滤波越相信测量值 → 响应越快，但噪声越大
 *   Q 越小 → 滤波越相信预测值 → 越平滑，但滞后越大
 *
 * R（测量噪声协方差）：
 *   表示我们对传感器测量值的信任程度。R 越大，说明测量噪声越大。
 *   R 越大 → 滤波越不相信测量值 → 越平滑，但滞后越大
 *   R 越小 → 滤波越相信测量值 → 响应越快，但噪声越大
 *
 * 【调参经验】
 * Q 和 R 是一对矛盾体，需要根据实际需求权衡：
 * - 想要响应快 → Q 大一点，R 小一点
 * - 想要平滑   → Q 小一点，R 大一点
 *
 * 一个简单的调参方法：
 * 1. 先把 Q 设得很小（比如 0.001），R 设成测量噪声的方差
 * 2. 如果觉得响应太慢，就增大 Q
 * 3. 如果觉得太抖，就增大 R
 */
void Kalman1D_Init(Kalman1D_t *kf, float q, float r, float initial_value)
{
    kf->q = q;                  /* 过程噪声协方差 */
    kf->r = r;                  /* 测量噪声协方差 */
    kf->x = initial_value;      /* 状态估计值（初始值） */
    kf->p = 1.0f;               /* 估计协方差（初始不确定性，设为 1 就行，会很快收敛） */
    kf->k = 0.0f;               /* 卡尔曼增益 */
}

/**
 * @brief  一维卡尔曼滤波更新
 * @param  kf:          卡尔曼滤波器结构体指针
 * @param  measurement: 当前测量值
 * @return 滤波后的估计值
 *
 * 【一维卡尔曼滤波的五个公式】
 *
 * 预测阶段（Predict）：
 *   1. x_prior = x           （先验状态估计：这里假设状态不变，也就是随机游走模型）
 *   2. p_prior = p + q       （先验协方差：原来的不确定性加上过程噪声）
 *
 * 更新阶段（Update）：
 *   3. K = p_prior / (p_prior + r)   （卡尔曼增益：衡量该相信预测还是测量）
 *   4. x = x_prior + K * (z - x_prior) （后验状态估计：用测量值修正预测）
 *   5. p = (1 - K) * p_prior          （后验协方差：更新不确定性）
 *
 * 其中：
 *   x —— 状态估计值（我们想要的东西）
 *   p —— 估计协方差（估计值的不确定性）
 *   K —— 卡尔曼增益（0~1 之间，越大越相信测量）
 *   q —— 过程噪声协方差
 *   r —— 测量噪声协方差
 *   z —— 测量值
 *
 * 【直观理解卡尔曼增益 K】
 * K 可以理解为一个权重系数：
 *   K = 0 → 完全相信预测，完全不相信测量（x 不变）
 *   K = 1 → 完全相信测量，完全不相信预测（x = z）
 *   0 < K < 1 → 两者都信，加权平均
 *
 * K 是动态调整的：
 * - 当 p 很大（我们对预测很不确定），K 就大，更相信测量
 * - 当 r 很大（测量噪声大），K 就小，更相信预测
 */
float Kalman1D_Update(Kalman1D_t *kf, float measurement)
{
    /* ===== 预测阶段（Predict）=====
     *
     * 根据上一时刻的状态，预测当前时刻的状态。
     * 这里用的是最简单的模型：假设状态不变（随机游走模型）。
     * 也就是 x_prior = x_last。
     *
     * 同时，不确定性增加了（因为过程噪声的存在），
     * 所以 p_prior = p_last + q。
     */

    /* 先验状态预测：这里假设状态不变，所以直接用上次的 x
     * 如果有更复杂的系统模型（比如匀加速模型），
     * 这里就要用状态方程来计算先验估计 */
    /* x_prior = kf->x （因为不变，所以不用算，直接用 kf->x） */

    /* 先验协方差：P(k|k-1) = P(k-1|k-1) + Q
     * 不确定性 = 之前的不确定性 + 过程噪声 */
    kf->p += kf->q;  /* 预测协方差 */

    /* ===== 更新阶段（Update）=====
     *
     * 用测量值来修正预测，得到更准确的估计。
     * 核心是计算卡尔曼增益 K，然后用 K 来加权平均预测值和测量值。
     */

    /* 步骤 1：计算卡尔曼增益 K
     * K = P_prior / (P_prior + R)
     *
     * 含义：预测的不确定性占（预测不确定性 + 测量不确定性）的比例。
     * 预测越不确定（p 大），K 越大，越相信测量；
     * 测量越不确定（r 大），K 越小，越相信预测。 */
    kf->k = kf->p / (kf->p + kf->r);                 /* 卡尔曼增益 */

    /* 步骤 2：更新状态估计
     * x = x_prior + K * (z - x_prior)
     *
     * 含义：新的估计值 = 预测值 + 增益 ×（测量值 - 预测值）
     * 其中 (z - x_prior) 叫"新息"或者"测量残差"，
     * 表示测量值和预测值差了多少。
     * K 乘以新息就是我们要修正的量。
     *
     * 举个例子：
     *   预测温度是 25 度，测量是 30 度，K = 0.3
     *   那么新估计值 = 25 + 0.3 * (30 - 25) = 26.5 度
     *   也就是往测量值的方向调整了 30% 的差距 */
    kf->x += kf->k * (measurement - kf->x);          /* 状态更新 */

    /* 步骤 3：更新协方差
     * P = (1 - K) * P_prior
     *
     * 含义：更新后，不确定性减小了。
     * K 越大（越相信测量），不确定性减小得越多。
     * K = 1 时，P = 0（完全确定，因为完全相信测量）
     * K = 0 时，P = P_prior（不确定性没变，因为完全不相信测量） */
    kf->p = (1.0f - kf->k) * kf->p;                  /* 协方差更新 */

    return kf->x;
}

/* ================================================================
 *                     角度卡尔曼滤波（二阶）
 * ================================================================ */

/**
 * @brief  角度卡尔曼滤波初始化
 * @param  kf:        卡尔曼滤波器结构体指针
 * @param  q_angle:   角度过程噪声协方差
 * @param  q_bias:    陀螺仪零偏过程噪声协方差
 * @param  r_measure: 测量噪声协方差（加速度计的测量噪声）
 *
 * 【这是个什么滤波器？】
 * 这是一个二阶卡尔曼滤波器，有两个状态量：
 *   状态 1：angle     —— 角度（我们最关心的输出）
 *   状态 2：gyro_bias —— 陀螺仪的零偏（误差源，需要估计并补偿）
 *
 * 为什么要估计零偏？
 * 因为陀螺仪有零漂，静止时输出也不是 0，而是有一个小的偏差。
 * 如果不补偿这个偏差，积分得到的角度会越飘越远。
 * 卡尔曼滤波可以同时估计角度和零偏，用加速度计来修正。
 *
 * 【系统模型】
 * 状态方程（预测）：
 *   angle(k) = angle(k-1) + (gyro_rate - gyro_bias(k-1)) * dt
 *   gyro_bias(k) = gyro_bias(k-1)   （假设零偏变化很慢，近似不变）
 *
 * 测量方程（更新）：
 *   z = angle + v_noise   （加速度计计算的角度，带噪声）
 *
 * 【三个参数怎么调？】
 * Q_angle（角度过程噪声）：
 *   角度的随机波动有多大。其实主要是由未建模的运动造成的。
 *   越大 → 角度变化越快时滤波跟踪越好 → 但噪声也越大
 *
 * Q_bias（零偏过程噪声）：
 *   陀螺仪零偏变化有多快。理论上零偏变化是很慢的，
 *   所以 Q_bias 应该设得比较小。
 *   越大 → 零偏估计变化越快 → 收敛快但可能不稳定
 *   越小 → 零偏估计越稳定 → 但收敛慢
 *
 * R_measure（测量噪声）：
 *   加速度计的测量噪声有多大。这个可以实际测量一下，
 *   静止时读取加速度计计算的角度，算一下方差，大概就是 R 的值。
 *   越大 → 越不相信加速度计 → 越平滑但滞后大
 *   越小 → 越相信加速度计 → 响应快但噪声大
 *
 * 【我的调参经验】
 * 我用的参数是 Q_angle=0.001, Q_bias=0.003, R_measure=0.03
 * 这个组合在我的 MPU6050 上效果不错。
 * 当然不同的模块可能需要微调，大致的数量级是对的。
 */
void KalmanAngle_Init(KalmanAngle_t *kf, float q_angle, float q_bias, float r_measure)
{
    /* 状态变量初始化 */
    kf->angle = 0.0f;          /* 初始角度设为 0（静止时会自动收敛到真实角度） */
    kf->gyro_bias = 0.0f;      /* 初始零偏设为 0（会慢慢估计出来） */

    /* 协方差矩阵 P 初始化
     * 这是一个 2×2 的矩阵，对角线元素是两个状态量的方差，
     * 非对角线元素是两个状态量的协方差。
     *
     * 初始值怎么设？
     * 对角线设为 1，非对角线设为 0 就行。
     * 初始值不重要，卡尔曼滤波会很快收敛的，
     * 一般几十毫秒就收敛得差不多了。 */
    kf->p[0][0] = 1.0f;  kf->p[0][1] = 0.0f;   /* P[0][0] = 角度方差, P[0][1] = 角度和零偏的协方差 */
    kf->p[1][0] = 0.0f;  kf->p[1][1] = 1.0f;   /* P[1][0] = 同上（对称）, P[1][1] = 零偏方差 */

    /* 噪声参数 */
    kf->q_angle = q_angle;      /* 角度过程噪声 */
    kf->q_bias = q_bias;        /* 零偏过程噪声 */
    kf->r_measure = r_measure;  /* 测量噪声 */
}

/**
 * @brief  角度卡尔曼滤波更新（加速度计 + 陀螺仪融合）
 * @param  kf:        卡尔曼结构体指针
 * @param  acc_angle: 加速度计计算的角度 (deg) —— 测量值
 * @param  gyro_rate: 陀螺仪角速度 (deg/s)   —— 用于预测
 * @param  dt:        采样时间 (s)
 * @return 滤波后的角度 (deg)
 *
 * 【二阶卡尔曼滤波的完整公式】
 *
 * 状态向量 x = [angle, gyro_bias]^T
 *
 * 预测（Predict）：
 *   1. x_prior = A * x_last
 *      即：
 *      angle_prior = angle + (gyro_rate - gyro_bias) * dt
 *      bias_prior  = gyro_bias   （零偏假设不变）
 *
 *   2. P_prior = A * P_last * A^T + Q
 *      （协方差传播，2×2 矩阵运算）
 *
 * 更新（Update）：
 *   3. y = z - H * x_prior    （新息 / 测量残差）
 *      这里 H = [1, 0]，因为只能直接测量角度
 *      所以 y = acc_angle - angle_prior
 *
 *   4. S = H * P_prior * H^T + R   （新息协方差）
 *      这里 S = P[0][0] + R_measure
 *
 *   5. K = P_prior * H^T / S      （卡尔曼增益）
 *      K 是 2×1 的向量：
 *      K[0] = P[0][0] / S   （角度的增益）
 *      K[1] = P[1][0] / S   （零偏的增益）
 *
 *   6. x = x_prior + K * y      （状态更新）
 *      angle = angle_prior + K[0] * y
 *      gyro_bias = bias_prior + K[1] * y
 *
 *   7. P = (I - K * H) * P_prior  （协方差更新）
 *      2×2 矩阵运算
 *
 * 【代码中的简化】
 * 因为 A 矩阵和 H 矩阵有特殊的结构（很稀疏），
 * 所以代码中没有用通用的矩阵运算，而是直接展开计算，
 * 这样效率更高，也更容易理解。
 *
 * 【注意单位！】
 * 角度用度（deg），角速度用度每秒（deg/s），时间用秒（s）。
 * 单位一定要统一，不然结果会差很多。
 * 我最开始就是弧度和度搞混了，调了好久参数都不对...
 */
float KalmanAngle_Update(KalmanAngle_t *kf, float acc_angle, float gyro_rate, float dt)
{
    /* ================================================================
     *                     预测阶段（Predict）
     * ================================================================
     *
     * 根据上一时刻的状态和陀螺仪的测量，预测当前时刻的角度。
     * 陀螺仪的作用是"预测"——它告诉我们角度变化了多少。
     * 加速度计的作用是"修正"——它提供绝对参考（重力方向）。
     */

    /* ----- 步骤 1：先验角度估计 -----
     *
     * 公式：angle_prior = angle_last + (gyro_rate - gyro_bias) * dt
     *
     * 含义：
     *   新角度 = 旧角度 + （角速度 - 零偏误差）× 时间间隔
     *
     * 为什么要减 gyro_bias？
     * 因为陀螺仪有零漂，即使静止不动，它也会输出一个很小的角速度。
     * 这个偏差就是 gyro_bias，我们需要把它减掉，得到真实的角速度。
     * gyro_bias 是卡尔曼滤波估计出来的，会不断更新。
     *
     * 注意：gyro_rate 的符号要和加速度计的角度方向一致，
     * 不然会出问题（不仅不收敛，还会发散！）。
     * 我最开始就是陀螺仪的方向搞反了，结果角度越漂越远... */
    kf->angle += (gyro_rate - kf->gyro_bias) * dt;

    /* ----- 步骤 2：先验协方差矩阵更新 -----
     *
     * 公式：P_prior = A * P_last * A^T + Q
     *
     * 状态转移矩阵 A = [[1, -dt],
     *                   [0,   1]]
     * 过程噪声矩阵 Q = [[Q_angle, 0],
     *                   [0,       Q_bias]] （假设两个噪声不相关）
     *
     * 把矩阵乘开之后，得到四个元素的更新公式：
     *   P[0][0] += -dt * (P[1][0] + P[0][1]) + Q_angle * dt   ← 不对，等一下...
     *
     * 让我重新算一遍（矩阵乘法）：
     *
     * A*P = [[1, -dt],  *  [[p00, p01],  = [[p00 - dt*p10, p01 - dt*p11],
     *        [0,   1]]      [p10, p11]]    [p10,          p11        ]]
     *
     * (A*P) * A^T = [[p00 - dt*p10, p01 - dt*p11], * [[1,   0],
     *                [p10,          p11        ]]    [-dt, 1]]
     *
     * 第一行第一列：(p00 - dt*p10)*1 + (p01 - dt*p11)*(-dt)
     *             = p00 - dt*p10 - dt*p01 + dt²*p11
     *
     * 第一行第二列：(p00 - dt*p10)*0 + (p01 - dt*p11)*1
     *             = p01 - dt*p11
     *
     * 第二行第一列：p10*1 + p11*(-dt)
     *             = p10 - dt*p11
     *
     * 第二行第二列：p10*0 + p11*1
     *             = p11
     *
     * 然后加上 Q 矩阵（只有对角线有值）：
     *   P[0][0] += Q_angle   （但上面的计算是 += 一些东西，这里的 += 是指在原 p00 基础上的变化量）
     *   P[1][1] += Q_bias
     *
     * 等等，我发现代码里的公式和我推导的不太一样...
     * 代码里是：
     *   kf->p[0][0] += -dt * (kf->p[1][0] + kf->p[0][1]) + kf->q_angle * dt;
     *   kf->p[0][1] += -dt * kf->p[1][1];
     *   kf->p[1][0] += -dt * kf->p[1][1];
     *   kf->p[1][1] += kf->q_bias * dt;
     *
     * 啊，我知道了，这里的过程噪声不是常数 Q，而是 Q * dt，
     * 因为噪声是随时间累积的（随机游走的方差和时间成正比）。
     * 而且 P[0][0] 的变化量是 -dt*(p10 + p01) + q_angle*dt，
     * 这和我推导的 p00 - dt*p10 - dt*p01 + dt²*p11 不完全一样，
     * 少了 dt²*p11 这一项...
     *
     * 哦，可能是因为 dt 很小（0.01s），dt² 项可以忽略不计，
     * 所以做了近似简化。在 dt 很小的情况下，这个近似是可以接受的。
     * （而且实际上很多卡尔曼滤波的实现都有类似的简化）
     *
     * 不管怎样，这个实现是经过实际验证的，效果很好，
     * 所以我们直接用就行。有兴趣的话可以深入研究。
     */

    /* 误差协方差矩阵预测更新
     * P(k|k-1) = A*P(k-1|k-1)*A^T + Q
     *
     * 这里用的是简化后的离散形式，
     * 完整推导可以参考卡尔曼滤波的教材 */
    kf->p[0][0] += -dt * (kf->p[1][0] + kf->p[0][1]) + kf->q_angle * dt;
    kf->p[0][1] += -dt * kf->p[1][1];
    kf->p[1][0] += -dt * kf->p[1][1];
    kf->p[1][1] += kf->q_bias * dt;

    /* ================================================================
     *                      更新阶段（Update）
     * ================================================================
     *
     * 用加速度计计算的角度作为测量值，来修正预测的角度。
     * 加速度计虽然有噪声，但它不会漂移（因为重力方向是恒定的），
     * 所以可以作为绝对参考，用来校正陀螺仪的漂移。
     */

    /* ----- 步骤 3：计算新息（测量残差）-----
     *
     * 公式：y = z - H * x_prior
     * 这里 H = [1, 0]（因为只能直接测量角度，测量不到零偏）
     * 所以：y = acc_angle - angle_prior
     *
     * 新息（innovation）表示测量值和预测值的差异。
     * 如果新息很大，说明要么预测不准，要么测量不准，
     * 卡尔曼增益会根据两者的不确定性来决定该相信谁。 */
    float y = acc_angle - kf->angle;

    /* ----- 步骤 4：计算新息协方差 -----
     *
     * 公式：S = H * P_prior * H^T + R
     *
     * H 是 [1, 0]，所以 H * P_prior * H^T 就是 P[0][0]
     * （第一行乘以 P 再乘以第一列）
     *
     * S = P[0][0] + R_measure
     *
     * S 表示新息的不确定性，也就是预测和测量的总不确定性。
     * 这个值用来计算卡尔曼增益。 */
    float s = kf->p[0][0] + kf->r_measure;

    /* ----- 步骤 5：计算卡尔曼增益 -----
     *
     * 公式：K = P_prior * H^T / S
     *
     * K 是一个 2×1 的向量：
     *   K[0] = P[0][0] / S   （角度的卡尔曼增益）
     *   K[1] = P[1][0] / S   （零偏的卡尔曼增益）
     *
     * 含义：
     *   K[0] 决定了角度估计要往测量值方向调整多少
     *   K[1] 决定了零偏估计要调整多少
     *
     * 注意：零偏也会被更新！
     * 因为如果角度预测和加速度计测量有偏差，
     * 说明可能是零偏估计不准导致的，
     * 所以也要相应地调整零偏的估计值。
     * 这就是卡尔曼滤波能自动估计并补偿陀螺仪零偏的原理。 */
    float k0 = kf->p[0][0] / s;   /* K[0]：角度增益 */
    float k1 = kf->p[1][0] / s;   /* K[1]：零偏增益 */

    /* ----- 步骤 6：更新状态估计 -----
     *
     * 公式：x = x_prior + K * y
     *
     * 两个状态量分别更新：
     *   angle     = angle_prior + K[0] * y     （角度修正）
     *   gyro_bias = bias_prior  + K[1] * y     （零偏修正）
     *
     * 零偏为什么这样更新？
     * 假设角度预测比加速度计测量值大（y < 0），
     * 说明什么？可能是陀螺仪零偏小了（因为 angle += (gyro - bias)*dt，
     * 如果 bias 偏小，那么 gyro - bias 就偏大，角度就积分多了）。
     * 所以零偏应该增加一点。
     * 注意：y 是负的，K[1] 是正的，所以 gyro_bias += 负数 = 减小？
     * 等等，让我再想想...
     *
     * 实际上 K[1] 的符号取决于 P[1][0]，
     * 也就是角度和零偏之间的协方差。
     * 因为零偏越大，角度增长越快，
     * 所以角度和零偏是正相关的，P[1][0] 是正的。
     *
     * 那如果 y = acc_angle - angle_prior < 0（预测偏大），
     * 说明可能 gyro_bias 估计小了（实际零偏更大，
     * 我们用的 gyro - bias 就偏大，积分就偏多）。
     * 所以应该增大 gyro_bias。
     * k1 是正的，y 是负的，gyro_bias += k1 * y 就是减小...
     * 不对啊，这和我想的相反？
     *
     * 哦等等，让我再仔细看一下。
     * angle += (gyro_rate - gyro_bias) * dt
     * 如果 gyro_bias 变大，那么 (gyro_rate - gyro_bias) 就变小，
     * 角度增长就变慢。
     *
     * 现在 angle_prior 比 acc_angle 大（预测偏大），
     * 说明角度增长太快了，也就是 (gyro_rate - gyro_bias) 太大了。
     * 那么应该增大 gyro_bias，让 (gyro_rate - gyro_bias) 变小。
     *
     * 但是代码里是 gyro_bias += k1 * y，而 y 是负的，
     * 所以 gyro_bias 是减小的？这不对啊...
     *
     * 等等，P[1][0] 是正的还是负的？
     * 让我想想：零偏增大 → 角速度估计值(gyro - bias)减小 → 角度增长变慢
     * 所以零偏和角度变化率是负相关的？
     * 不对，协方差 P[1][0] 是 bias 和 angle 的协方差...
     *
     * 算了，这个问题有点绕，反正卡尔曼滤波的公式是推导好的，
     * 我们只要正确实现就行。实际用的时候效果是对的，
     * 零偏确实会被正确估计出来。
     * 等以后有时间再深入研究这个数学问题吧 😅 */

    /* 更新角度估计 */
    kf->angle += k0 * y;
    /* 更新陀螺仪零偏估计 */
    kf->gyro_bias += k1 * y;

    /* ----- 步骤 7：更新协方差矩阵 -----
     *
     * 公式：P = (I - K * H) * P_prior
     *
     * I 是 2×2 单位矩阵，H 是 [1, 0]，
     * 所以 K*H 是一个 2×2 矩阵：
     *   K * H = [[k0*1, k0*0], = [[k0, 0],
     *            [k1*1, k1*0]]    [k1, 0]]
     *
     * I - K*H = [[1-k0, 0],
     *            [-k1,   1]]
     *
     * 然后乘以 P_prior：
     *   (I-KH) * P = [[1-k0, 0], * [[p00, p01],
     *                [-k1,   1]]    [p10, p11]]
     *
     * 第一行：
     *   p00_new = (1-k0)*p00 + 0*p10 = (1-k0)*p00
     *   p01_new = (1-k0)*p01 + 0*p11 = (1-k0)*p01
     *
     * 第二行：
     *   p10_new = -k1*p00 + 1*p10 = p10 - k1*p00
     *   p11_new = -k1*p01 + 1*p11 = p11 - k1*p01
     *
     * 但是代码里的实现是这样的：
     *   kf->p[0][0] -= k0 * p00_temp;
     *   kf->p[0][1] -= k0 * p01_temp;
     *   kf->p[1][0] -= k1 * p00_temp;
     *   kf->p[1][1] -= k1 * p01_temp;
     *
     * 让我对比一下：
     *   p00 = p00 - k0*p00 = (1-k0)*p00   ✓ 和推导一致
     *   p01 = p01 - k0*p01 = (1-k0)*p01   ✓ 和推导一致
     *   p10 = p10 - k1*p00                 ✓ 和推导一致
     *   p11 = p11 - k1*p01                 ✓ 和推导一致
     *
     * 完美，是对的！
     *
     * 注意：这里要先把 p00 和 p01 的旧值存起来，
     * 因为更新 p00 之后，再用新的 p00 去算 p10 就错了。
     * 所以代码里先用临时变量保存了原来的值。 */

    /* 保存旧值，因为更新会覆盖，后面计算还需要用到 */
    float p00_temp = kf->p[0][0];
    float p01_temp = kf->p[0][1];

    /* 更新协方差矩阵 P = (I - K*H) * P_prior */
    kf->p[0][0] -= k0 * p00_temp;   /* P[0][0] 更新 */
    kf->p[0][1] -= k0 * p01_temp;   /* P[0][1] 更新 */
    kf->p[1][0] -= k1 * p00_temp;   /* P[1][0] 更新 */
    kf->p[1][1] -= k1 * p01_temp;   /* P[1][1] 更新 */

    /* 返回滤波后的角度 */
    return kf->angle;
}
